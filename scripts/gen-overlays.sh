#!/usr/bin/env bash
# Recompile BBS's code overlays (PSP_GAME/USRDIR/MODULE/*.ELF: title screen, menus, minigames). They all load at the
# same address (0x08B8BF08), one at a time, so each gets its own renamed symbols and host/overlays.cpp swaps their
# functions in when the game loads one. Usage: gen-overlays.sh <psp_recomp> <MODULE dir> <out dir>
set -euo pipefail
RECOMP=$1; MODDIR=$2; OUT=$3
rm -rf "$OUT.new"; mkdir -p "$OUT.new"
REG=$OUT.new/overlays_registry.cpp
{
  echo '// Generated by scripts/gen-overlays.sh. Derived from the game: never commit.'
  echo '#include "overlays.hpp"'
  echo 'namespace psprecomp { class Runtime; }'
} > "$REG"
NAMES=()
for elf in "$MODDIR"/*.ELF; do
  n=$(basename "$elf" .ELF); NAMES+=("$n")
  "$RECOMP" "$elf" --auto "$OUT.new/$n" 0 > "$OUT.new/$n.log" 2>&1 || { echo "FAIL $n"; tail -3 "$OUT.new/$n.log"; exit 1; }
  for f in "$OUT.new/$n"/*.cpp "$OUT.new/$n"/*.hpp; do
    sed -i -e "s/recomp_unit_\([0-9]\)/recomp_unit_ov${n}_\1/g" \
           -e "s/register_generated_unit_/register_ov${n}_unit_/g" \
           -e "s/register_generated_functions/register_ov${n}/g" "$f"
  done
  rm -f "$OUT.new/$n/auto_codegen_report.json"
  { echo "namespace psprecomp { void register_ov${n}(Runtime &); }"
    echo "static const std::uint32_t kAddr_${n}[] = {"
    grep -ohE 'register_function\(0x[0-9A-F]+u' "$OUT.new/$n"/generated_unit_*.cpp | sed 's/register_function(/  /; s/$/,/'
    echo "};"; } >> "$REG"
done
{
  echo "const bbs::OverlayInfo bbs::kOverlays[] = {"
  for n in "${NAMES[@]}"; do
    echo "  {\"$n\", &psprecomp::register_ov${n}, kAddr_${n}, sizeof(kAddr_${n}) / sizeof(kAddr_${n}[0])},"
  done
  echo "};"
  echo "const std::size_t bbs::kOverlayCount = ${#NAMES[@]};"
} >> "$REG"
# Addresses below the window that the overlays call or jump to: the main executable's recompile must make them
# function entries (PSPRECOMP_EXTRA_SEEDS=<this file> for 3-GENERATE).
# The window starts at the lowest overlay load address (0x08B8BF08 on the US disc, 0x08B6EE80 on Final Mix).
elf_vaddr() {  # first program header's p_vaddr, as 8 uppercase hex digits
  local phoff; phoff=$(od -A n -t u4 -j 28 -N 4 "$1" | tr -d ' ')
  printf '%08X\n' "0x$(od -A n -t x4 -j $((phoff + 8)) -N 4 "$1" | tr -d ' ')"
}
WIN=$(for elf in "$MODDIR"/*.ELF; do elf_vaddr "$elf"; done | sort | head -1)
echo "overlay window starts at 0x$WIN"
grep -ohE '(ctx\.pc = |, )0x08[0-9A-F]{6}u' "$OUT.new"/*/generated_unit_*.cpp | grep -oE '08[0-9A-F]{6}'   | awk -v win="$WIN" '$1 >= "08804000" && $1 < win' | sort -u > "$OUT.new/main_seeds.txt"
rm -rf "$OUT"; mv "$OUT.new" "$OUT"
echo "overlays: ${NAMES[*]}"
